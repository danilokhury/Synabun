let translate = null;
export function setAntigravityTranslator(fn) { translate = typeof fn === 'function' ? fn : null; }

/** The sentence for `key`, translated when the locale has it, else the English, with {name} placeholders filled. */
export function agyText(key, params) {
  const path = `antigravityPanel.${key}`;
  let value = path;
  try { value = translate?.(path, params) || path; } catch { value = path; }
  if (value !== path) return value;
  const english = Object.hasOwn(AGY_COPY, key) ? AGY_COPY[key] : key;
  return english.replace(/\{(\w+)\}/g, (_, name) => (params?.[name] ?? `{${name}}`));
}
