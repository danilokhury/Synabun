// ═══════════════════════════════════════════
// WA-VIEW — what Settings → WhatsApp shows for a status
// ═══════════════════════════════════════════
//
// Pure (no DOM, no fetch): waView(status) turns GET /api/whatsapp/status into
// the header and the setup pane — { dot, title, sub, primary, secondary, step,
// pane, nav } — for every state the service reports, and this file holds every
// sentence the tab shows, so tests can read them and ui-whatsapp.js only
// places them. Strings are plain text; the tab escapes whatever it inserts.

// ── Translation ──
// The English in this file is the source text. Without a translator (tests, Node) every string reads as
// written. Settings installs one with setTranslator((key, english, params) => string); the keys are
// settings.redesign.wa.<path> (generated by docs/design/settings-redesign/tools/wa_keys.mjs) and `{name}`
// marks a value filled in at run time.
let translate = null;
export function setTranslator(fn) { translate = typeof fn === 'function' ? fn : null; }
const fill = (text, params) => (params ? String(text).replace(/\{(\w+)\}/g, (m, k) => (params[k] != null ? params[k] : m)) : text);
const say = (key, english, params) => (translate ? translate(`settings.redesign.wa.${key}`, english, params) : fill(english, params));
/** One entry of a table of sentences (STAGE_TEXT, ERROR_TEXT …), or its fallback entry. */
const pick = (prefix, table, id, fallback) => {
  const key = Object.prototype.hasOwnProperty.call(table, id) ? id : fallback;
  return key == null ? '' : say(`${prefix}.${key}`, table[key]);
};
const NOT_COPY = new Set(['id', 'value', 'key', 'name']);
const segment = (v) => String(v).replace(/[^A-Za-z0-9_-]+/g, '');
/**
 * A copy of a constant in the reader's language. Arrays of objects are keyed by their id / value / key / name,
 * plain arrays by index; identifiers (id, value, key, name) are never translated.
 */
export function localize(prefix, data) {
  if (typeof data === 'string') return data ? say(prefix, data) : data;
  if (Array.isArray(data)) {
    return data.map((item, i) => {
      const named = item && typeof item === 'object' && !Array.isArray(item) ? (item.id ?? item.value ?? item.key ?? item.name) : undefined;
      return localize(`${prefix}.${named != null ? segment(named) : i}`, item);
    });
  }
  if (data && typeof data === 'object') return Object.fromEntries(Object.entries(data).map(([k, v]) => [k, NOT_COPY.has(k) ? v : localize(`${prefix}.${k}`, v)]));
  return data;
}

