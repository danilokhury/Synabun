/**
 * The stored choice of a status: { provider, model, effort } or null (same as
 * the Assistant). A status without the field (an older server) reads as null.
 */
export function brainChoiceOf(status) {
  const choice = status?.brainChoice?.choice ?? status?.config?.brain ?? null;
  if (!choice || typeof choice !== 'object' || typeof choice.provider !== 'string' || typeof choice.model !== 'string' || !choice.model) return null;
  return { provider: choice.provider, model: choice.model, effort: typeof choice.effort === 'string' && choice.effort ? choice.effort : null };
}
/** The choice in use: the stored one unless the server fell back to the default (a disabled or unknown model). */
export function brainChoiceInUse(status) {
  return status?.brainChoice?.fallback ? null : brainChoiceOf(status);
}
/**
 * The model button's text: "Same as the Assistant" (with the brain that is, when
 * the server says) or "Codex · GPT-6 Sol". `modelLabel`: the picker's own name for the model.
 */
export function brainChoiceLabel(status, { modelLabel = '' } = {}) {
  const choice = brainChoiceInUse(status);
  const effective = status?.brainChoice?.effective || null;
  if (!choice) {
    const same = say('brain.same', 'Same as the Assistant');
    const now = effective?.provider ? [effective.providerLabel || brainProviderLabel(effective.provider), effective.modelLabel || effective.model].filter(Boolean).join(' · ') : '';
    return now ? say('brain.sameNow', '{same} ({now})', { same, now }) : same;
  }
  return `${brainProviderLabel(choice.provider)} · ${modelLabel || effective?.modelLabel || choice.model}`;
}
/**
 * The notes under the model: why a stored choice is not in use, and that a
 * brain other than Claude runs the conversation read-only (the existing rule).
 */
export function brainChoiceNotes(status) {
  const view = status?.brainChoice;
  if (!view || typeof view !== 'object') return [];
  const notes = [];
  const fallback = view.fallback;
  if (fallback?.model) {
    notes.push(fallback.reason === 'disabled'
      ? say('brain.fallbackDisabled', '{model} is switched off in the Assistant\'s Models list, so WhatsApp runs on the same brain as the Assistant. Pick another model here, or switch it back on.', { model: fallback.model })
      : say('brain.fallbackUnknown', '{provider} no longer lists {model}, so WhatsApp runs on the same brain as the Assistant. Pick another model here.', { provider: fallback.providerLabel || brainProviderLabel(fallback.provider), model: fallback.model }));
  }
  if (view.readOnly?.provider) {
    notes.push(say('brain.readOnly', 'On {brain}, a WhatsApp conversation runs read-only whatever the level: only a Claude model can ask on your phone before it acts. Pick a Claude model for Ask on my phone or Autonomous.', { brain: view.readOnly.label || brainProviderLabel(view.readOnly.provider) }));
  }
  return notes;
}

