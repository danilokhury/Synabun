/** 125000 → "2:05"; negative → "0:00". */
export function formatCountdown(ms) {
  const total = Math.max(0, Math.ceil((Number(ms) || 0) / 1000));
  const h = Math.floor(total / 3600);
  const m = Math.floor((total % 3600) / 60);
  const s = total % 60;
  return h ? `${h}:${String(m).padStart(2, '0')}:${String(s).padStart(2, '0')}` : `${m}:${String(s).padStart(2, '0')}`;
}
/** A clock time for an epoch ms ("14:05"). */
export function clockTime(ms) {
  const d = new Date(Number(ms));
  return Number.isFinite(d.getTime()) ? `${String(d.getHours()).padStart(2, '0')}:${String(d.getMinutes()).padStart(2, '0')}` : '';
}

function accountLine(status) {
  const account = status?.account;
  if (!account) return '';
  const name = typeof account.name === 'string' && account.name.trim() && account.name !== '~' ? account.name.trim() : '';
  return [name, account.masked].filter(Boolean).join(' · ');
}
