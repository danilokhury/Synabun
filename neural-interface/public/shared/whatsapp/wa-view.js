/**
 * @param {object} status  GET /api/whatsapp/status (or null while it loads)
 * @param {{now?: number}} [opts]
 * @returns {{dot:'ok'|'warn'|'err'|'dim', title:string, sub:string, primary:{id,label}|null, secondary:{id,label}|null, step:string|null, pane:string, nav:'connected'|'disconnected'}}
 */
export function waView(status, { now = Date.now() } = {}) {
  const s = status && typeof status === 'object' ? status : {};
  if (s.ok === false) {
    return view('err', say('view.unavailable.title', 'WhatsApp settings are unavailable'), s.status === 404 ? say('view.unavailable.noSupport', 'This SynaBun server has no WhatsApp support yet. Restart it after updating.') : String(s.error || say('view.unavailable.noAnswer', 'No answer from SynaBun.')), { pane: 'unavailable' });
  }
  const level = levelLabel(s.level);
  const mode = modeLabel(s.mode);
  switch (s.state) {
    case 'unavailable':
      // reason: 'starting' (the server is still booting the Assistant), 'error' (the WhatsApp Link failed to load), 'env' (the kill switch).
      if (s.reason === 'starting') return view('dim', say('view.starting.title', 'WhatsApp is starting'), say('view.starting.sub', 'SynaBun is still starting its Assistant. This updates by itself in a few seconds.'), { pane: 'unavailable' });
      if (s.reason === 'error') return view('err', say('view.loadFailed.title', 'WhatsApp could not start'), say('view.loadFailed.sub', 'The WhatsApp Link failed to load on this computer. The SynaBun server log says why; restart SynaBun once it is fixed.'), { pane: 'unavailable' });
      return view('dim', say('view.off.title', 'WhatsApp is turned off on this computer'), say('view.off.sub', 'SYNABUN_WHATSAPP=off is set where SynaBun runs. Remove it and restart SynaBun to use WhatsApp.'), { pane: 'unavailable' });
    case 'not_installed':
      return view('dim', say('view.notInstalled.title', 'Not set up'), say('view.notInstalled.sub', 'Chat with your SynaBun Assistant from WhatsApp. Choose how below; it takes about a minute.'), { primary: button('setup', say('button.setup', 'Set up WhatsApp')), step: 'choose', pane: 'choose' });
    case 'ready':
      return view('dim', say('view.ready.title', 'Ready to link'), say('view.ready.sub', 'The connector is installed. Choose how you want to chat, then scan one QR code.'), { primary: button('setup', say('button.link', 'Link WhatsApp')), step: 'choose', pane: 'choose' });
    case 'installing': {
      const size = connectorSize(s);
      const downloading = size ? say('view.installing.downloadingSized', 'Downloading the connector ({size}, once)…', { size }) : say('view.installing.downloading', 'Downloading the connector…');
      return view('warn', say('view.installing.title', 'Setting up the WhatsApp connector'), s.stage === 'downloading' ? downloading : pick('stage', STAGE_TEXT, s.stage, 'checking'), { secondary: button('cancel-install', say('button.cancel', 'Cancel')), step: 'install', pane: 'installing' });
    }
    case 'install_failed':
      return view('err', say('view.installFailed.title', 'The connector could not be installed'), pick('installError', INSTALL_ERRORS, s.code, 'UNKNOWN'), { primary: button('retry-install', say('button.tryAgain', 'Try again')), secondary: button('show-log', say('button.showLog', 'Show install log')), step: 'install', pane: 'install_failed' });
    case 'linking': {
      if (s.phase === 'scanned') return view('warn', say('view.scanned.title', 'Phone accepted, finishing the link…'), say('view.scanned.sub', 'Keep WhatsApp open on the phone for a few seconds.'), { secondary: button('cancel-link', say('button.cancel', 'Cancel')), step: 'link', pane: s.method === 'code' ? 'code' : 'qr' });
      if (s.method === 'code') return view('warn', say('view.code.title', 'Enter the code on your phone'), say('view.code.sub', 'WhatsApp → Settings → Linked devices → Link a device → Link with phone number instead.'), { secondary: button('cancel-link', say('button.cancel', 'Cancel')), step: 'link', pane: 'code' });
      return view('warn', say('view.qr.title', 'Scan the QR code with WhatsApp'), say('view.qr.sub', 'On the phone: WhatsApp → Settings → Linked devices → Link a device.'), { secondary: button('cancel-link', say('button.cancel', 'Cancel')), step: 'link', pane: 'qr' });
    }
    case 'link_expired':
      return view('warn', say('view.expired.title', 'The code expired'), say('view.expired.sub', 'Nothing was linked. Try again when your phone is ready.'), { primary: button('relink', say('button.newCode', 'Show a new code')), secondary: button('change-setup', say('button.changeSetup', 'Change setup')), step: 'link', pane: 'expired' });
    case 'confirm_owner': {
      if (s.confirm?.kind === 'code' || (s.mode === 'dedicated' && s.confirm?.kind !== 'self')) {
        return view('warn', say('view.claim.title', 'Claim the second number from your own WhatsApp'), say('view.claim.sub', 'Send the one-time code from your personal WhatsApp to the linked number. Only that account can then talk to SynaBun.'), { primary: button('claim', say('button.claim', 'Show the claim code')), secondary: button('unlink', say('button.unlink', 'Unlink')), step: 'confirm', pane: 'claim' });
      }
      const who = accountLine(s);
      const linked = who ? say('view.confirm.linkedAs', 'Linked as {who}.', { who }) : say('view.confirm.linked', 'A WhatsApp account is linked.');
      const left = s.confirm?.expiresAt ? ` ${say('view.confirm.within', 'Confirm within {time}, or it is logged out.', { time: formatCountdown(s.confirm.expiresAt - now) })}` : '';
      return view('warn', say('view.confirm.title', 'Is this your WhatsApp?'), `${linked}${left}`, { primary: button('confirm', say('button.confirm', 'This is me — start')), secondary: button('reject', say('button.reject', 'Not me? Unlink')), step: 'confirm', pane: 'confirm_self' });
    }
    case 'connected': {
      const who = accountLine(s);
      const until = s.level === 'autonomous' && s.levelExpiresAt ? ` ${say('view.connected.until', 'until {time}', { time: clockTime(s.levelExpiresAt) })}` : '';
      // A Codex / OpenCode brain holds the conversation at read-only whatever the level.
      const applies = s.brainLimit?.provider ? say('view.connected.readOnlyBrain', 'Read-only ({brain} brain)', { brain: s.brainLimit.label || s.brainLimit.provider }) : `${level}${until}`;
      return view('ok', say('view.connected.title', 'Connected'), [mode, who, applies].filter(Boolean).join(' · '), { primary: button('open-conversation', say('button.openConversation', 'Open conversation')), secondary: button('test', say('button.test', 'Send a test message')), step: 'done', pane: 'connected', nav: 'connected' });
    }
    case 'reconnecting': {
      const next = s.connection?.nextRetryAt ? s.connection.nextRetryAt - now : null;
      const sub = next !== null && next > 0
        ? say('view.reconnecting.retry', 'Connection lost. Attempt {attempt}; trying again in {time}.', { attempt: Math.max(1, Number(s.connection.attempt) || 1), time: formatCountdown(next) })
        : say('view.reconnecting.connecting', 'Connecting to WhatsApp…');
      return view('warn', say('view.reconnecting.title', 'Reconnecting'), sub, { primary: button('reconnect', say('button.reconnectNow', 'Reconnect now')), step: 'done', pane: 'reconnecting' });
    }
    case 'paused': {
      const sub = s.enabled === false ? say('view.paused.off', 'WhatsApp is linked but turned off. Resume to act on messages again.')
        : s.pausedBy === 'phone' ? say('view.paused.phone', 'Paused from your phone with /pause. Resume here, or send /resume.')
          : say('view.paused.computer', 'Paused from this computer. SynaBun does not act on WhatsApp messages until you resume (the phone cannot undo this).');
      return view('warn', say('view.paused.title', 'Paused'), sub, { primary: button('resume', say('button.resume', 'Resume')), step: 'done', pane: 'paused' });
    }
    case 'logged_out': {
      const reason = Object.prototype.hasOwnProperty.call(LOGOUT_TEXT, s.reason) ? s.reason : 'removed';
      return view('err', say(`logout.${reason}.title`, LOGOUT_TEXT[reason].title), say(`logout.${reason}.sub`, LOGOUT_TEXT[reason].sub), { primary: s.reason === 'banned' ? null : button('relink', say('button.linkAgain', 'Link again')), secondary: s.reason === 'banned' ? button('change-setup', say('button.setupAgain', 'Set up again')) : null, step: 'link', pane: 'logged_out' });
    }
    case 'error': {
      const canReconnect = !['RUNTIME_MISSING'].includes(s.code);
      return view('err', say('view.error.title', 'WhatsApp needs attention'), ERROR_TEXT[s.code] ? pick('error', ERROR_TEXT, s.code) : say('view.error.stopped', 'The WhatsApp link stopped ({code}).', { code: String(s.code || say('view.error.unknown', 'unknown error')) }), {
        primary: s.code === 'OWNER_ANOMALY' ? (s.mode === 'dedicated' ? button('reset-owner', say('button.resetOwner', 'Confirm the owner again')) : button('unlink', say('button.unlinkRelink', 'Unlink and link again'))) : s.code === 'RUNTIME_MISSING' ? button('retry-install', say('button.installAgain', 'Install again')) : canReconnect ? button('reconnect', say('button.reconnect', 'Reconnect')) : null,
        secondary: button('show-log', say('button.showLog', 'Show install log')), pane: 'error',
      });
    }
    default:
      return view('dim', say('view.loading.title', 'Checking WhatsApp…'), say('view.loading.sub', 'Asking SynaBun for the WhatsApp status.'), { pane: 'loading' });
  }
}

/** The masked account and owner lines for the confirm card ("Linked as Ana · ••••1234"). */
export function confirmLine(status) {
  const who = accountLine(status);
  return who ? say('confirmLine.as', 'Linked as {who}', { who }) : say('confirmLine.plain', 'Linked');
}

