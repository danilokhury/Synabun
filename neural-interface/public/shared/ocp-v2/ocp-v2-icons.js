// SynaBun logo — matches Claude Code panel rendering
const SYNABUN_ICON = '<img src="logoHD.png" alt="" style="width:14px;height:14px;object-fit:contain;">';

export function toolIcon(name) {
  if (name && (name.startsWith('SynaBun_') || name.startsWith('mcp__SynaBun__'))) return SYNABUN_ICON;
  const key = (name || '').toLowerCase().replace(/[^a-z]/g, '');
  return TOOL_ICONS[key] || TOOL_ICONS.bash;
}
