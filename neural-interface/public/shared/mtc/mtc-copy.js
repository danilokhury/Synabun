let _translate = null;
export function setMaritacaTranslator(fn) { _translate = typeof fn === 'function' ? fn : null; }

function fill(template, params = {}) {
  return String(template).replace(/\{(\w+)\}/g, (m, k) => (params[k] === undefined || params[k] === null ? m : String(params[k])));
}

/** The sentence `key` names, translated when the page has a translator, else the English above. */
export function mtcText(key, params = {}) {
  const fallback = MTC_COPY[key];
  if (_translate) {
    try {
      const value = _translate(`maritacaPanel.${key}`, params);
      if (typeof value === 'string' && value && value !== `maritacaPanel.${key}`) return value;
    } catch { /* fallback below */ }
  }
  return fallback === undefined ? key : fill(fallback, params);
}
