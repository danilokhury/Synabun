/** The locale for a browser's language list (navigator.languages, chrome.i18n.getUILanguage()). */
export function popupLocale(languages = []) {
  const list = (Array.isArray(languages) ? languages : [languages]).filter(Boolean).map(String);
  return /^pt\b/i.test(list[0] || '') ? 'pt-BR' : 'en';
}
/** A translator for one locale: English behind it key by key, {name} filled from params; an unknown key is the key. */
export function translator(locale = 'en') {
  const active = POPUP_STRINGS[locale] || POPUP_STRINGS.en;
  return (key, params) => {
    let value = active[key] ?? POPUP_STRINGS.en[key];
    if (typeof value !== 'string') return key;
    if (params) value = value.replace(/\{(\w+)\}/g, (all, name) => (params[name] != null ? String(params[name]) : all));
    return value;
  };
}
