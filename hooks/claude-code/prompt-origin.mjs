/**
 * Who wrote this "prompt"?
 *
 * UserPromptSubmit fires for text the human typed AND for text Claude Code or
 * SynaBun injects on the human's behalf: background-agent notifications,
 * cross-session messages, mailbox relays, local-command output, continuation
 * banners. The hook input carries no origin field, so the text is the only
 * signal. System text must never be judged, recalled against, counted as a
 * human message or matched by the English conversation regexes (on 2026-09-23
 * a task notification quoting "continue where we left off" triggered the
 * past-conversation workflow three times in one session).
 *
 * Pure and dependency-free: the Neural Interface assistant imports it too.
 */

// Checked against the start of the text, both before and after the wrappers
// below are removed. Order is irrelevant; the marker names are for logs/tests.
const SYSTEM_MARKERS = [
  ['task-notification', /^<task-notification>/i],
  ['system-notification', /^\[SYSTEM NOTIFICATION\b/i],
  ['cross-session-message', /^<cross-session-message\b/i],
  ['cross-session-idle', /^\[Cross-session idle notice\]/i],
  ['teammate-message', /^<teammate-message\b/i],
  ['synabun-mailbox', /^\[SynaBun Mailbox\]/i],
  ['synabun-router', /^\[SynaBun Router\]/i],
  ['synabun-browser', /^\[SynaBun Browser\]/i],
  ['synabun-loop', /^\[SynaBun Loop\]/i],
  ['native-loop', /^NATIVE LOOP ITERATION:/],
  ['continuation', /^This session is being continued from a previous conversation/i],
  ['local-command', /^<local-command-(?:stdout|stderr|caveat)>/i],
  ['bash-output', /^<bash-(?:stdout|stderr)>/i],
  ['local-command-caveat', /^Caveat: The messages below were generated by the user while running local commands/i],
  // A skill's expanded instructions (the human typed a slash command).
  ['skill-instructions', /^<skill-instructions>/i],
];

// Wrappers the IDE or another hook adds around what the human typed. They
// never carry the human's own words, so they are removed wherever they occur.
const DROPPED_WRAPPERS = ['ide_opened_file', 'system-reminder', 'user-prompt-submit-hook'];
const SELECTION_CLIP = 800;

function stripWrappers(text) {
  let out = text;
  for (const tag of DROPPED_WRAPPERS) {
    out = out.replace(new RegExp(`<${tag}(?:\\s[^>]*)?>[\\s\\S]*?</${tag}>`, 'gi'), ' ');
  }
  // An editor selection is context the human pointed at: keep it, bounded.
  out = out.replace(/<ide_selection(?:\s[^>]*)?>([\s\S]*?)<\/ide_selection>/gi,
    (_m, inner) => ` ${String(inner).trim().slice(0, SELECTION_CLIP)} `);
  return out.replace(/[ \t]+\n/g, '\n').replace(/\n{3,}/g, '\n\n').trim();
}

function systemMarker(text) {
  for (const [marker, re] of SYSTEM_MARKERS) if (re.test(text)) return marker;
  return null;
}

/**
 * @param {unknown} raw  The prompt as delivered to the hook.
 * @returns {{origin:'system'|'human', text:string, marker:string|null}}
 *   `text` is the prompt with IDE/hook wrappers removed (for both origins).
 */
export function classifyPrompt(raw) {
  const original = typeof raw === 'string' ? raw.trim() : '';
  const early = systemMarker(original);
  const text = stripWrappers(original);
  if (early) return { origin: 'system', text, marker: early };
  const late = systemMarker(text);
  if (late) return { origin: 'system', text, marker: late };
  return { origin: 'human', text, marker: null };
}

// WHOLE-string patterns. The old prefix patterns (`^(yes|no|ok)\b`) dropped
// real prompts such as "no, the bug is in X" before any judgment or recall.
const TRIVIAL_PATTERNS = [
  /^\s*$/,
  /^(?:yes|yeah|yep|no|nope|nah|ok(?:ay)?|k|sure|thanks|thank you|ty|thx|perfect|great|good|nice|cool|got it|sounds good|lgtm|do it|go ahead|proceed|continue|keep going|next|done|stop|cancel|abort|never ?mind|nvm)[\s.!?,]*$/i,
  // Slash commands and their transcript form: Claude Code handles these.
  /^\/[\w:.-]+(?:\s[\s\S]*)?$/,
  /^<command-(?:name|message|args)>/i,
  // A word or two ("fix it", "why?"): too little to search memory with.
  /^[\s\S]{1,7}$/,
  /^\[Image #\d+\]$/,
  // Open a named file, nothing more.
  /^(?:read|open|show|cat|look at|check)\s+(?:me\s+)?(?:the\s+)?(?:file\s+)?\S+\.\w{1,5}$/i,
  // A bare command line, not a request that mentions one.
  /^(?:run|execute|start|npm|node|git|pnpm|yarn|bun)(?:\s+\S+){1,4}$/i,
];

/** True when a (human) prompt can never benefit from a judgment or recall. */
export function isTrivialPrompt(text) {
  const trimmed = typeof text === 'string' ? text.trim() : '';
  return TRIVIAL_PATTERNS.some((pattern) => pattern.test(trimmed));
}
