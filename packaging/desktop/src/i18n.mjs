/** 'pt-BR' when the first preferred language that SynaBun has is Portuguese, else 'en'. */
export function pickLocale(preferred = [], saved = null) {
  if (saved === 'en' || saved === 'pt-BR') return saved;
  for (const tag of Array.isArray(preferred) ? preferred : [preferred]) {
    const lower = String(tag || '').toLowerCase();
    if (lower.startsWith('pt')) return 'pt-BR';
    if (lower.startsWith('en')) return 'en';
  }
  return 'en';
}

/** The sentence for `key` in `locale`, English when the locale lacks it, `{name}` filled from `params`. */
export function translate(locale, key, params = {}) {
  const template = STRINGS[locale]?.[key] ?? STRINGS.en[key] ?? key;
  return String(template).replace(/\{(\w+)\}/g, (all, name) => (params[name] != null ? String(params[name]) : all));
}
